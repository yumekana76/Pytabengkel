-- ---------------------------------------------------------------------
--  TRIGGER PENDAFTARAN PENGGUNA
--  Saat ada user baru di auth.users, buat profile + data customer.
--  Kalau email-nya sudah ada di tabel customers, akunnya DIHUBUNGKAN
--  ke customer tersebut (bukan membuat data ganda).
-- ---------------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_customer_id bigint;
  v_nama        text;
  v_telepon     text;
  v_alamat      text;
  v_role        public.user_role;
begin
  v_nama    := coalesce(nullif(new.raw_user_meta_data ->> 'nama', ''), split_part(new.email, '@', 1));
  v_telepon := coalesce(new.raw_user_meta_data ->> 'telepon', '');
  v_alamat  := coalesce(new.raw_user_meta_data ->> 'alamat', '');

-- Semua pendaftaran baru dimulai sebagai customer.
-- Admin harus ditetapkan secara manual oleh pemilik database.
v_role := 'customer'::public.user_role;

  -- Coba hubungkan ke data customer yang sudah ada
  select id into v_customer_id
  from public.customers
  where lower(email) = lower(new.email)
  limit 1;

  -- Customer baru (bukan admin) -> buat data customer
  if v_customer_id is null and v_role = 'customer' then
    insert into public.customers (nama, telepon, email, alamat, registered_via)
    values (v_nama, v_telepon, new.email, v_alamat, 'customer')
    returning id into v_customer_id;
  end if;

  insert into public.profiles (id, nama, telepon, email, alamat, role, customer_id)
  values (new.id, v_nama, v_telepon, new.email, v_alamat, v_role, v_customer_id)
  on conflict (id) do update
    set nama        = excluded.nama,
        telepon     = excluded.telepon,
        email       = excluded.email,
        alamat      = excluded.alamat,
        customer_id = excluded.customer_id,
        updated_at  = now();

  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------------------------------------------------------------------
--  SINKRON EMAIL PROFIL DARI SUPABASE AUTH
--  profiles.email hanya boleh ditulis trigger ini (guard_profile_write
--  mengunci kolom itu untuk customer). Saat email login berubah di
--  Supabase Auth — termasuk lewat menu ganti email halaman Profil dan
--  setelah tautan konfirmasi dibuka — baris profil ikut diperbarui,
--  sehingga daftar akun admin & tampilan sesi tidak pernah basi.
-- ---------------------------------------------------------------------
create or replace function public.sync_profile_email()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.email is distinct from old.email then
    update public.profiles
    set email = new.email,
        updated_at = now()
    where id = new.id;
  end if;

  return new;
end $$;

drop trigger if exists sync_profile_email on auth.users;
create trigger sync_profile_email
  after update of email on auth.users
  for each row execute function public.sync_profile_email();

-- ---------------------------------------------------------------------
--  RPC: ensure_my_profile()
--  ---------------------------------------------------------------------
--  Dipanggil klien (js/supabase.js -> loadProfile) kalau SELECT ke
--  profiles tidak mengembalikan baris — mis. user dibuat manual di
--  dashboard Supabase sehingga trigger on_auth_user_created tidak
--  pernah jalan, atau policy INSERT self (guard: profiles insert
--  admin) menolak pembuatan profil oleh customer itu sendiri.
--
--  security definer: fungsi berjalan dengan hak pemilik (owner), jadi
--  tidak terhalang RLS INSERT di atas. Idempoten: kalau profil sudah
--  ada, tidak ada yang diubah — baris lama dikembalikan apa adanya.
--  search_path dikunci supaya tidak bisa diselundupi lewat schema
--  buatan pemanggil.
-- ---------------------------------------------------------------------
create or replace function public.ensure_my_profile()
returns setof public.profiles
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid         uuid := auth.uid();
  v_customer_id bigint;
  v_nama        text;
  v_telepon     text;
  v_alamat      text;
  v_email       text;
  v_row         public.profiles%rowtype;
begin
  if v_uid is null then
    raise exception 'Tidak ada sesi login (auth.uid kosong)';
  end if;

  select * into v_row from public.profiles where id = v_uid;

  if found then
    return next v_row;
    return;
  end if;

  select email,
         coalesce(raw_user_meta_data ->> 'nama', ''),
         coalesce(raw_user_meta_data ->> 'telepon', ''),
         coalesce(raw_user_meta_data ->> 'alamat', '')
    into v_email, v_nama, v_telepon, v_alamat
    from auth.users
   where id = v_uid;

  v_email := coalesce(v_email, '');
  v_nama  := coalesce(
    nullif(v_nama, ''),
    nullif(split_part(v_email, '@', 1), ''),
    'Customer'
  );

  -- Hubungkan ke data customer yang sudah ada (jangan membuat ganda).
  select id into v_customer_id
    from public.customers
   where lower(email) = lower(v_email)
   limit 1;

  if v_customer_id is null then
    insert into public.customers (nama, telepon, email, alamat, registered_via)
    values (v_nama, v_telepon, v_email, v_alamat, 'customer')
    returning id into v_customer_id;
  end if;

  insert into public.profiles (id, nama, telepon, email, alamat, role, customer_id)
  values (v_uid, v_nama, v_telepon, v_email, v_alamat, 'customer', v_customer_id)
  on conflict (id) do nothing;

  select * into v_row from public.profiles where id = v_uid;
  return next v_row;
end $$;

grant execute on function public.ensure_my_profile() to authenticated;

-- ---------------------------------------------------------------------
--  RPC: admin_set_user_role()
--  ---------------------------------------------------------------------
--  Satu-satunya jalur resmi untuk mengubah role akun dari halaman
--  Kelola Pengguna. security definer + pengecekan is_super_admin()
--  membuat aturan tetap berlaku walau RLS sebuah baris mengizinkan
--  UPDATE. Pengaman tambahan:
--    * super admin tidak bisa menurunkan role akunnya sendiri;
--    * super admin terakhir tidak bisa diturunkan.
--  Role dikirim sebagai teks lalu di-cast, sehingga tidak memakai
--  literal enum 'super_admin' di dalam body fungsi.
-- ---------------------------------------------------------------------
create or replace function public.admin_set_user_role(p_user uuid, p_role text)
returns public.profiles
language plpgsql
security definer
set search_path = public
as $$
declare
  v_role        public.user_role;
  v_row         public.profiles%rowtype;
  v_super_count integer;
begin
  if not public.is_super_admin() then
    raise exception 'Hanya super admin yang boleh mengubah role pengguna';
  end if;

  if p_user is null then
    raise exception 'Akun pengguna tidak ditemukan';
  end if;

  if p_role is null or p_role not in ('customer', 'admin', 'super_admin') then
    raise exception 'Role tidak dikenal: %', coalesce(p_role, '(kosong)');
  end if;

  if p_user = auth.uid() then
    raise exception 'Anda tidak dapat mengubah role akun sendiri';
  end if;

  select * into v_row from public.profiles where id = p_user;

  if not found then
    raise exception 'Akun pengguna tidak ditemukan';
  end if;

  if v_row.role::text = 'super_admin' and p_role <> 'super_admin' then
    select count(*) into v_super_count
      from public.profiles
     where role::text = 'super_admin';

    if v_super_count <= 1 then
      raise exception 'Minimal harus ada satu super admin';
    end if;
  end if;

  v_role := p_role::public.user_role;

  update public.profiles
     set role = v_role,
         updated_at = now()
   where id = p_user
   returning * into v_row;

  return v_row;
end $$;

revoke all on function public.admin_set_user_role(uuid, text) from public;
