-- Bolehkah user yang sedang login menilai service ini?
-- Syarat: service miliknya sendiri DAN sudah selesai.
-- Dipakai policy INSERT/UPDATE reviews supaya ulasan tidak bisa
-- dilekatkan ke service orang lain atau service yang belum selesai.
create or replace function public.can_review(p_service_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.services s
    where s.id = p_service_id
      and s.customer_id = public.my_customer_id()
      and s.status = 'Selesai'
  );
$$;

-- ---------------------------------------------------------------------
--  PENJAGA KOLOM SENSITIF (trigger)
--  RLS mengatur BARIS, bukan KOLOM — tanpa trigger ini customer bisa
--  mengubah kolom paling sensitif di baris miliknya sendiri:
--    * profiles.role      -> eskalasi diri jadi admin
--    * profiles.email     -> promosi diri via perintah admin berbasis email
--    * profiles.customer_id -> membajak data customer lain
--    * services.pembayaran/status/biaya -> memalsukan pembayaran
-- ---------------------------------------------------------------------

create or replace function public.guard_profile_write()
returns trigger
language plpgsql
as $$
begin
  /* Operasi SQL langsung (tanpa JWT) lewat. */
  if auth.uid() is not null then
    /* Perubahan role adalah hak super admin. Admin biasa tetap bisa
       mengelola data operasional, tetapi tidak bisa menaikkan role
       siapa pun (termasuk dirinya sendiri). */
    if new.role is distinct from old.role then
      if not public.is_super_admin() then
        raise exception 'Hanya super admin yang boleh mengubah role pengguna';
      end if;

      if new.id = auth.uid() then
        raise exception 'Super admin tidak dapat mengubah role akunnya sendiri';
      end if;
    end if;

    if not public.is_admin() then
      if new.id is distinct from old.id
         or new.customer_id is distinct from old.customer_id then
        raise exception 'Anda tidak boleh mengubah role atau tautan data customer';
      end if;

      /* Email profil juga dikunci. Email login yang otoritatif ada di
         Supabase Auth (auth.users) dan disinkronkan ke kolom ini lewat
         trigger sync_profile_email. Tanpa penguncian ini customer bisa
         menyetel email profilnya menjadi admin@workshop.com lalu terpromosi
         lewat perintah admin lama yang berbasis email (lihat blok
         "CARA MENJADIKAN SEBUAH AKUN ADMIN / SUPER ADMIN" di bawah). */
      if new.email is distinct from old.email then
        raise exception 'Email profil tidak bisa diubah langsung; email login diubah lewat menu ganti email';
      end if;
    end if;
  end if;
  return new;
end $$;

create or replace function public.guard_service_write()
returns trigger
language plpgsql
as $$
begin
  /* Admin (JWT admin) dan operasi SQL langsung (tanpa JWT) bebas. */
  if auth.uid() is null or public.is_admin() then
    return new;
  end if;

  if tg_op = 'INSERT' then
    /* Request dari customer SELALU dimulai sebagai antrean baru
       yang masih menunggu persetujuan admin. */
    new.status       := 'Menunggu';
    new.pembayaran   := 'Belum Lunas';
    new.biaya_jasa   := 0;
    new.spareparts   := '[]'::jsonb;
    new.mechanic_id  := null;
    new.mekanik      := '';
    new.requested_by := 'customer';
    new.approval     := 'Menunggu';
    new.approval_note := '';
    return new;
  end if;

  /* UPDATE: kolom sensitif dikembalikan ke nilai lama (bukan error)
     supaya simpanan cache usang di portal customer tetap berhasil —
     nilai server yang menang, upaya pemalsuan diabaikan diam-diam. */
  new.status      := old.status;
  new.pembayaran  := old.pembayaran;
  new.biaya_jasa  := old.biaya_jasa;
  new.spareparts  := old.spareparts;
  new.mechanic_id := old.mechanic_id;
  new.mekanik     := old.mekanik;
  new.customer_id := old.customer_id;
  /* Persetujuan ajuan hanya boleh diubah admin — customer tidak
     bisa menyetujui ajuannya sendiri lewat cache/usang. */
  new.approval      := old.approval;
  new.approval_note := old.approval_note;
  return new;
end $$;

